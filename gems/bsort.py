import sort
import ssort
import time
import random



rang=int(input("Number of elements: "))

start = time.perf_counter()

rarr = [random.randint(1, rang) for _ in range(rang)]
sort.sorting(rarr)

end = time.perf_counter()

print(f"Elapsed time: {end - start:.4f} seconds\n\n")



